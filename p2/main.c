#include <stdio.h> // scanf, printf 사용

int main()
{
int N; // 입력받을 정수 개수
int a[20], b[20]; // 최대 20개까지 저장할 배열 2개
int *p, *q; // 배열 접근용 포인터

scanf("%d", &N); // N 입력
// 조건: 1 <= N <= 20

for (p = a; p < a + N; p++) // p가 a[0]부터 a[N-1]까지 이동
{
scanf("%d", p); // p가 가리키는 위치에 입력값 저장
// &a[i] 대신 p를 사용한 것
}

for (p = b; p < b + N; p++) // p가 b[0]부터 b[N-1]까지 이동
{
scanf("%d", p); // b 배열에도 입력값 저장
}

q = b + N - 1; // q를 b 배열의 마지막 원소에 연결
// N=4면 q는 b[3]을 가리킴

for (p = a; p < a + N; p++) // p는 a 배열을 앞에서부터 이동
{
printf(" %d", *p + *q); // a의 현재 값 + b의 현재 값 출력
// p는 앞에서부터, q는 뒤에서부터
// 문제 조건처럼 앞에 공백 있는 " %d" 형태

q--; // q를 한 칸 앞으로 이동
// b[N-1] → b[N-2] → ... → b[0]
}

return 0; // 정상 종료
}
